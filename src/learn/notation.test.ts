import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { LESSONS } from '../content';
import { modernLesson } from './notation';

const texts = (l: (typeof LESSONS)[number]) => l.steps.flatMap((s) => [...('paragraphs' in s ? s.paragraphs : []), ...('before' in s ? (s.before ?? []) : []), ...('after' in s ? s.after : [])]);

describe('lessons in modern notation (owner, 2026-11-20)', () => {
  it.each(LESSONS.map((l) => [l.id, l] as const))('%s: no move is left in the old notation', (_id, lesson) => {
    const { unresolved } = modernLesson(lesson);
    expect(unresolved).toEqual([]);
  });

  it('Lasker: pieces and pawn moves', () => {
    const l = modernLesson(LESSONS.find((x) => x.id === 'lasker-opening-development')!).lesson;
    const t = texts(l).join(' ');
    expect(t).toContain('After (1) e4, e5 the only Pawn');
    expect(t).toContain('(2) Bc4, Bc5; (3) Nf3, Nc6; (4) d3, Nf6; (5) Nc3, d6; (6) O-O, O-O; (7) Bg5.');
    expect(t).toContain('(2) ...., exd4; (3) Qxd4');
  });

  it('Lasker: a pawn capture names its file, and checks are marked as today', () => {
    const t = texts(modernLesson(LESSONS.find((x) => x.id === 'lasker-checkmate')!).lesson).join(' ');
    expect(t).toContain('(1) e4, e5; (2) f4, Bc5; (3) fxe5??');
    expect(t).toContain('Qh4+');
  });

  it('Capablanca: descriptive notation read through the game', () => {
    const t = texts(modernLesson(LESSONS.find((x) => x.id === 'capablanca-opening-strategy')!).lesson).join(' ');
    expect(t).toContain('1 e4  or 1 d4');
    expect(t).toMatch(/1\. e4\s+e5 2\. Nf3/);
    expect(t).toContain('4. Bb5');
  });

  it('the moves a first version got wrong (review of ADR-064) are right', () => {
    const shown = (id: string) => texts(modernLesson(LESSONS.find((x) => x.id === id)!).lesson).join(' ');
    const strategy = shown('capablanca-opening-strategy');
    expect(strategy).toMatch(/6\. d3\s+d6/);
    expect(strategy).toContain('7. Bg5');
    expect(strategy).toContain('win quickly by Nd5');
    const centre = shown('capablanca-control-of-centre');
    expect(centre).toContain('If Nf6;');
    expect(centre).toContain('Qb3 wins a Pawn.');
    expect(centre).toContain('h3 and a3');
    expect(shown('lasker-double-attack')).not.toMatch(/Bb5\+/);
    expect(shown('lasker-mate-in-two')).not.toMatch(/Rh5\+/);
    expect(shown('lasker-mating-positions')).toMatch(/Nf7#|Nf7 mate/);
    const queen = shown('lasker-queen-mate');
    // "White checkmates by (7) Q-a7 or (7) Q-b5": Black's reply is not written, so the moves are
    // written from their text, without a sign the book does not give (never a false "+").
    expect(queen).toContain('checkmates by (7) Qa7 or (7) Qb5');
    expect(shown('lasker-opening-threats')).toContain('dxc6');
  });

  it.each(LESSONS.map((l) => [l.id, l] as const))('%s: nothing of the old notation is left in the text', (_id, lesson) => {
    const t = texts(modernLesson(lesson).lesson).join(' ');
    expect(t).not.toMatch(/\bKt\b|\bP[a-h][1-8]x|\bO - O\b| ch\b|\b[KQRB]-[a-h][1-8]|\bP-[a-h][1-8]/);
    expect(t).not.toMatch(/[+#]\s+mate\b/);
  });

  it('the lesson as stored is not changed', () => {
    const l = LESSONS.find((x) => x.id === 'lasker-checkmate')!;
    const before = JSON.stringify(l);
    modernLesson(l);
    expect(JSON.stringify(l)).toBe(before);
  });

  it('the converted text is the reviewed snapshot (docs/audits/notation-snapshot.md)', () => {
    const lines = ['# Lessons in modern notation: every converted passage', '', 'Generated by `src/learn/notation.test.ts` (`WRITE_SNAPSHOT=1 npx vitest run src/learn/notation.test.ts`). Each passage as printed, then as shown. A change to the converter changes this file; read the difference before committing it.', ''];
    for (const l of LESSONS) {
      const shown = modernLesson(l).lesson;
      lines.push(`## ${l.id}`, '');
      const a = texts(l);
      const b = texts(shown);
      a.forEach((p, i) => {
        if (p !== b[i]) lines.push(`- printed: ${p.replace(/\s+/g, ' ')}`, `  shown:   ${b[i]!.replace(/\s+/g, ' ')}`, '');
      });
    }
    const md = `${lines.join('\n')}\n`;
    const path = 'docs/audits/notation-snapshot.md';
    if (process.env.WRITE_SNAPSHOT) writeFileSync(path, md);
    expect(readFileSync(path, 'utf8')).toBe(md);
  });
});
